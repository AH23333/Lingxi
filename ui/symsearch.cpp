std::vector<std::wstring> SymbolSearch(const std::wstring& query)
{
    std::vector<std::wstring> out;
    // 查询切词：空格/全角空格分隔，逐字符小写化
    std::vector<std::wstring> tokens;
    std::wstring cur;
    for (wchar_t c : query)
    {
        if (c == L' ' || c == L'\u3000')
        {
            if (!cur.empty()) { tokens.push_back(cur); cur.clear(); }
        }
        else
        {
            cur += (wchar_t)towlower(c);
        }
    }
    if (!cur.empty()) tokens.push_back(cur);
    if (tokens.empty()) return out;

    struct Hit { size_t idx; int score; };
    std::vector<Hit> hits;
    for (size_t i = 0; i < kKwCount; i++)
    {
        std::wstring kw = ToLower(kSymKw[i].kw);
        std::wstring sym = ToLower(kSymKw[i].sym);
        int score = 0;
        bool all = true;
        for (const auto& t : tokens)
        {
            if (HasToken(kw, t)) score += 2;                                   // 整词
            else if (kw.find(t) != std::wstring::npos ||
                     sym.find(t) != std::wstring::npos) score += 1;            // 子串
            else { all = false; break; }                                       // 一词未中即出局
        }
        if (all) hits.push_back({ i, score });
    }
    // 稳定排序：整词分高在前，同分保表序（面板分类顺序）
    std::stable_sort(hits.begin(), hits.end(), [](const Hit& a, const Hit& b) {
        return a.score > b.score;
    });
    for (const auto& h : hits)
    {
        if (out.size() >= kMaxResults) break;
        out.push_back(kSymKw[h.idx].sym);
    }
    return out;
}


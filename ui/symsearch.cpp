constexpr size_t kKwCount = sizeof(kSymKw) / sizeof(kSymKw[0]);
constexpr size_t kMaxResults = 96; // 面板 12 行 × 8 列

std::wstring ToLower(const wchar_t* s)
{
    std::wstring r;
    for (const wchar_t* p = s; *p; ++p)
        r += (wchar_t)towlower(*p);
    return r;
}

// 整词命中：needle 与 hay 按空格切分的某个词完全相等
bool HasToken(const std::wstring& hay, const std::wstring& needle)
{
    size_t start = 0;
    while (start <= hay.size())
    {
        size_t end = hay.find(L' ', start);
        if (end == std::wstring::npos) end = hay.size();
        if (end - start == needle.size() &&
            hay.compare(start, needle.size(), needle) == 0)
            return true;
        if (end == hay.size()) break;
        start = end + 1;
    }
    return false;
}

